/*******************************************************************************

In a ClusterGraph, each vertex represents a valid cluster from variant clustering.
Edges are generated by following the reads - if a read has markers in two 
different clusters, there is a connection between those clusters.

This graph allows visualization and analysis of how clusters are ordered
along reads, similar to how AnchorGraph shows anchor connectivity.

*******************************************************************************/

